import type { Inflection, SentenceExample, SentenceLessonSource } from './types.ts';

type FormSource = [
  initial: string,
  genitive: string,
  ru: string,
  note?: string,
  singular?: string,
];

type ExampleSource = [initial: string, pattern: string, ru: string];

interface GroupSource {
  id: string;
  title?: string;
  text: string;
  note: string;
  forms: FormSource[];
  extraForms?: FormSource[];
  phrases?: ExampleSource[];
  sentences?: ExampleSource[];
}

type BlockSource = SentenceLessonSource['blocks'][number];

function parseForm([initial, genitive, ru, note, singular]: FormSource): Inflection & { note?: string } {
  return { initial, answers: genitive.split(' / '), ru, note, singular };
}

function block(
  heading: Pick<BlockSource, 'id' | 'title' | 'rule'>,
  groups: GroupSource[],
): BlockSource {
  const formsByGroup = groups.map(({ forms, extraForms }) => ({
    table: forms.map(parseForm),
    extra: (extraForms ?? []).map(parseForm),
  }));
  const pool = formsByGroup.flatMap(({ table, extra }) => [...table, ...extra]);

  return {
    ...heading,
    detail: groups.map(({ title, text }, index) => ({
      title, text, forms: formsByGroup[index].table,
    })),
    examples: groups.flatMap((group, index) => {
      const { table, extra } = formsByGroup[index];
      const forms = [...table, ...extra];

      function example(
        id: string,
        initial: string,
        pattern: string,
        ru: string,
        complete: boolean,
      ): SentenceExample {
        const entry = forms.find((form) => form.initial === initial);
        if (!entry) throw new Error(`Не найдена начальная форма ${initial} в группе ${group.id}`);
        const atSentenceStart = complete && pattern.startsWith('___');
        const displayed = (form: string) =>
          atSentenceStart ? form[0].toUpperCase() + form.slice(1) : form;
        const answers = entry.answers.map(displayed);
        const distractors = [
          initial,
          ...pool.filter((other) => other.initial !== initial).flatMap((other) => other.answers),
        ].map(displayed);
        const options = [...new Set([...answers, ...distractors])].slice(0, 4);
        return {
          id: `genitive-${heading.id}-${group.id}-${id}`,
          form: answers[0],
          sentence: pattern.replace('___', answers[0]),
          ru,
          note: `${initial} → ${entry.answers.join(' / ')}. ${entry.note ?? group.note}`,
          choiceOnly: !complete,
          practiceGroup: group.id,
          choice: {
            wordIndex: pattern.split(' ').indexOf('___'),
            answers,
            options,
            instruction: answers.length > 1
              ? 'Выбери любую подходящую форму родительного падежа'
              : 'Выбери форму родительного падежа',
            cue: initial,
          },
        };
      }

      return [
        ...table.map(({ initial, ru }, position) =>
          example(`form-${position + 1}`, initial, '___', ru, false),
        ),
        ...(group.phrases ?? []).map(([initial, pattern, ru], position) =>
          example(`phrase-${position + 1}`, initial, pattern, ru, false),
        ),
        ...(group.sentences ?? []).map(([initial, pattern, ru], position) =>
          example(`sentence-${position + 1}`, initial, pattern, ru, true),
        ),
      ];
    }),
  };
}

